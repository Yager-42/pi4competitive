def validate_config(value: Any, source: str) -> Config:
    if not isinstance(value, dict):
        raise ValueError(f"{EXTENSION_NAME}: {source} must be an object")
    unknown = [key for key in value if key not in _CONFIG_KEYS]
    if unknown:
        raise ValueError(
            f"{EXTENSION_NAME}: unknown config keys in {source}: {', '.join(sorted(unknown))}"
        )
    config: dict[str, Any] = {**DEFAULT_CONFIG, **value}
    if (
        not isinstance(config["model"], str)
        or not config["model"].strip()
        or bool(re.search(r"\s", config["model"]))
        or ("/" in config["model"] and len(config["model"].split("/")) != 2)
    ):
        raise ValueError(f"{EXTENSION_NAME}: model must be a model id or provider/model")
    if config["reasoning"] not in _VALID_REASONING:
        raise ValueError(f"{EXTENSION_NAME}: invalid reasoning level")
    if not isinstance(config["timeoutMs"], int) or not 1_000 <= config["timeoutMs"] <= 120_000:
        raise ValueError(f"{EXTENSION_NAME}: timeoutMs must be 1000..120000")
    if not isinstance(config["maxTokens"], int) or not 256 <= config["maxTokens"] <= 4_096:
        raise ValueError(f"{EXTENSION_NAME}: maxTokens must be 256..4096")
    if not isinstance(config["retries"], int) or not 0 <= config["retries"] <= 2:
        raise ValueError(f"{EXTENSION_NAME}: retries must be 0..2")
    if config["failureMode"] not in ("deny", "defer"):
        raise ValueError(f"{EXTENSION_NAME}: failureMode must be deny or defer")
    if not isinstance(config["grantTtlMs"], int) or not 1_000 <= config["grantTtlMs"] <= 300_000:
        raise ValueError(f"{EXTENSION_NAME}: grantTtlMs must be 1000..300000")
    allows = config["autoConfirmBoundedAllows"]
    if (
        not isinstance(allows, (list, tuple))
        or any(surface not in _BOUNDED_SURFACES for surface in allows)
        or len(set(allows)) != len(allows)
    ):
        raise ValueError(
            f"{EXTENSION_NAME}: autoConfirmBoundedAllows must contain unique "
            "external_directory/path entries"
        )
    for name in ("maxUserTranscriptTokens", "maxToolTranscriptTokens", "maxRelevantResultTokens"):
        if not isinstance(config[name], int) or not 32 <= config[name] <= 8_000:
            raise ValueError(f"{EXTENSION_NAME}: {name} must be 32..8000")
    return {
        **config,
        "autoConfirmBoundedAllows": tuple(allows),
    }


def package_config_path() -> Path:
    return PACKAGE_ROOT / "config.json"


def _read_json_config(path: Path) -> Any:
    try:
        with path.open("r", encoding="utf-8") as handle:
            return json.load(handle)
    except Exception as error:
        raise ValueError(
            f"{EXTENSION_NAME}: cannot load {path}: {error if isinstance(error, Exception) else str(error)}"
        ) from error


def _env_overlay() -> dict[str, Any]:
    """App host delta: user-global ``~/.pi`` overlay replaced by ``AUTO_REVIEW_*`` env."""
    overlay: dict[str, Any] = {}
    for key, env_name in _ENV_OVERRIDE_KEYS.items():
        raw = os.environ.get(env_name)
        if raw is None:
            continue
        if key in _NUMERIC_ENV_KEYS:
            try:
                overlay[key] = int(raw)
            except ValueError as error:
                raise ValueError(f"{EXTENSION_NAME}: {env_name} must be an integer") from error
        else:
            overlay[key] = raw
    return overlay


def load_config() -> Config:
    """Package-shipped defaults from ``config.json`` plus ``AUTO_REVIEW_*`` env overlay."""
    return validate_config(
        {**_read_json_config(package_config_path()), **_env_overlay()},
        str(package_config_path()),
    )


def apply_user_config(
    package_config: Config, value: Any, source: str = "user config"
) -> Config:
    if not isinstance(value, dict):
        raise ValueError(f"{EXTENSION_NAME}: {source} must be an object")
    return validate_config(
        {
            **package_config,
            "autoConfirmBoundedAllows": list(package_config["autoConfirmBoundedAllows"]),
            **value,
        },
        source,
    )


def apply_project_config(trusted: Config, value: Any) -> Config:
    """Project config may only tighten the trusted config (upstream rules)."""
    if not isinstance(value, dict):
        raise ValueError(f"{EXTENSION_NAME}: project config must be an object")
    forbidden = [key for key in value if key not in _PROJECT_ALLOWED_KEYS]
    if forbidden:
        raise ValueError(
            f"{EXTENSION_NAME}: project config cannot set: {', '.join(sorted(forbidden))}"
        )
    merged: dict[str, Any] = dict(trusted)
    for key in _TIGHTENABLE_NUMBER_KEYS:
        if key not in value:
            continue
        raw = value[key]
        if (
            not isinstance(raw, (int, float))
            or isinstance(raw, bool)
            or not float(raw).is_integer()
            or raw > trusted[key]
        ):
            raise ValueError(
                f"{EXTENSION_NAME}: project {key} may only lower the trusted value"
            )
        merged[key] = int(raw)
    if "failureMode" in value:
        if value["failureMode"] != "deny":
            raise ValueError(f"{EXTENSION_NAME}: project failureMode may only be deny")
        merged["failureMode"] = "deny"
    if "autoConfirmBoundedAllows" in value:
        allows = value["autoConfirmBoundedAllows"]
        if not isinstance(allows, (list, tuple)) or any(
            not isinstance(surface, str) or surface not in trusted["autoConfirmBoundedAllows"]
            for surface in allows
        ):
            raise ValueError(
                f"{EXTENSION_NAME}: project autoConfirmBoundedAllows may only remove "
                "trusted surfaces"
            )
        merged["autoConfirmBoundedAllows"] = list(dict.fromkeys(allows))
    return validate_config(merged, "effective project config")


def _is_within(parent: str, child: str) -> bool:
    parent_path = Path(parent).resolve()
    child_path = Path(child).resolve()
    try:
        child_path.relative_to(parent_path)
        return True
    except ValueError:
        return False


def protected_write_hard_deny(request: BoundaryRequest) -> dict[str, str] | None:
    """Writing security extension code, policy, configuration, or audit data is forbidden."""
    is_write = request.get("surface") == "filesystem-write" or bool(
        request.get("operation")
        and re.search(r"\b(?:write|create|delete|rename|chmod|chown)\b", request["operation"])
    )
    if not is_write:
        return None
    target = request.get("resolvedPath") or request.get("path")
    if not target:
        return None
    cwd = request.get("cwd", "")
    resolved_target = str((Path(cwd) / target).resolve())
    protected_directories = [str(PACKAGE_ROOT)]
    protected_files = [
        str((Path(cwd) / ".pi" / "settings.json").resolve()),
        str((Path(cwd) / ".pi" / "sandbox.json").resolve()),
        str((Path(cwd) / PROJECT_CONFIG_PATH).resolve()),
    ]
    if any(_is_within(path, resolved_target) for path in protected_directories) or (
        resolved_target in protected_files
    ):
        return {
            "rule": "security-control-tampering",
            "reason": "writing security extension code, policy, configuration, or audit data is forbidden",
        }
    return None


def assert_trusted_installation(cwd: str, package_root: Path | None = None) -> None:
    root = package_root or PACKAGE_ROOT
    if _is_within(str(Path(cwd).resolve()), str(root.resolve())):
        raise ValueError(
            f"{EXTENSION_NAME}: refusing security policy loaded from agent-writable workspace {root}"
        )


def session_config(cwd: str, trusted: Config, allow_untrusted_workspace: bool) -> Config:
    if not allow_untrusted_workspace:
        assert_trusted_installation(cwd)
    project_path = Path(cwd) / PROJECT_CONFIG_PATH
    if not project_path.is_file():
        return Config(**trusted)
    raw = _read_json_config(project_path)
    return apply_project_config(trusted, raw)


def _parse_model_ref(model_ref: str) -> tuple[str | None, str]:
    if "/" not in model_ref:
        return None, model_ref
    provider, _, model_id = model_ref.partition("/")
    return provider, model_id


async def resolve_reviewer(
    registry: ModelRegistryView,
    config: Config,
    session_id: str = "pi-auto-review",
) -> ReviewerRuntime:
    provider, model_id = _parse_model_ref(config["model"])
    available = await registry.getAvailable()
    registered = (
        next(
            (
                candidate
                for candidate in available
                if candidate.get("provider") == provider and candidate.get("id") == model_id
            ),
            None,
        )
        if provider
        else next(
            (
                candidate for candidate in available
                if candidate.get("id") == model_id or candidate.get("name") == model_id
            ),
            None,
        )
    )
    provider_fallback = (
        next(
            (candidate for candidate in available if candidate.get("provider") == provider),
            None,
        )
        if provider
        else None
    )
    model: PiModel | None = registered
    if model is None and provider_fallback is not None:
        model = {**provider_fallback, "id": model_id, "name": model_id}
    if model is None:
        raise ValueError(
            f"provider {provider} is unavailable for custom model {config['model']}"
            if provider
            else f"model {config['model']} is unavailable"
        )
    auth = await registry.getAuth(model)
    if auth is None:
        raise ValueError("model authentication failed: unavailable")
    return {
        "model": model,
        "auth": auth.get("auth") or {},
        "sessionId": session_id,
    }


def _text_from_assistant(message: CompletionMessage) -> str:
    return "\n".join(
        part["text"]
        for part in (message.get("content") or [])
        if part.get("type") == "text" and isinstance(part.get("text"), str)
    ).strip()


def _shared_review_context(
    request: BoundaryRequest,
    transcript: TranscriptResult,
    reviewer_context: BoundaryReviewerContext | None,
) -> str:
    override = ""
    user_override = reviewer_context.get("userOverride") if reviewer_context else None
    if user_override:
        override = (
            "\n<trusted-user-override>\n"
            + json.dumps(user_override)
            + "\n</trusted-user-override>\n"
        )
    return (
        "<permission-request>\n"
        + json.dumps(request, indent=2)
        + "\n</permission-request>\n"
        + override
        + "\n<selected-transcript>\n"
        + transcript["text"]
        + "\n</selected-transcript>"
    )


async def _model_call(
    registry: ModelRegistryView,
    runtime: ReviewerRuntime,
    config: Config,
    controller: AbortController,
    shared_context: str,
    instruction: str,
    max_tokens: int,
) -> str:
    now_ms = int(asyncio.get_event_loop().time() * 1000)
    context: PiContext = {
        "systemPrompt": REVIEWER_SYSTEM_PROMPT,
        "messages": [
            {"role": "user", "content": shared_context, "timestamp": now_ms},
            {"role": "user", "content": instruction, "timestamp": now_ms},
        ],
    }
    options: dict[str, Any] = {}
    if runtime["auth"].get("apiKey") is not None:
        options["apiKey"] = runtime["auth"]["apiKey"]
    if runtime["auth"].get("headers") is not None:
        options["headers"] = runtime["auth"]["headers"]
    if runtime["auth"].get("env") is not None:
        options["env"] = runtime["auth"]["env"]
    options.update({
        "signal": controller.signal,
        "maxTokens": max_tokens,
        "cacheRetention": "short",
        "sessionId": runtime["sessionId"],
        "timeoutMs": config["timeoutMs"],
    })
    if config["reasoning"] != "off":
        options["reasoning"] = config["reasoning"]
    message = await registry.completeSimple(runtime["model"], context, options)
    if message.get("stopReason") != "stop":
        raise ValueError(
            f"model stopped with {message.get('stopReason') or 'unknown'}: "
            f"{message.get('errorMessage') or 'no details'}"
        )
    text = _text_from_assistant(message)
    if not text:
        raise ValueError("reviewer returned empty output")
    return text


async def complete(
    registry: ModelRegistryView,
    config: Config,
    request: BoundaryRequest,
    entries: list[Any],
    session_id: str,
    signal: AbortSignal | None,
    reviewer_context: BoundaryReviewerContext | None = None,
) -> ReviewResult:
    started = asyncio.get_event_loop().time()
    transcript = build_classifier_transcript(entries, config, request)
    shared_context = _shared_review_context(request, transcript, reviewer_context)
    controller = AbortController()
    if signal is not None and signal.aborted:
        controller.abort()
    elif signal is not None:
        # Host delta: the minimal AbortSignal has no remove_event_listener; the
        # listener only aborts an already-finished controller, so it is inert.
        signal.add_event_listener("abort", controller.abort)
    timeout_handle = asyncio.get_event_loop().call_later(
        config["timeoutMs"] / 1000, controller.abort
    )
    try:
        if controller.signal.aborted:
            raise ValueError("review aborted before model resolution")
        runtime = await resolve_reviewer(registry, config, session_id)
        last_error: Exception | None = None
        retry_errors: list[str] = []
        for attempt in range(1, config["retries"] + 2):
            try:
                decision = parse_decision(
                    await _model_call(
                        registry,
                        runtime,
                        config,
                        controller,
                        shared_context,
                        DETAILED_INSTRUCTION,
                        config["maxTokens"],
                    )
                )
                return ReviewResult(
                    decision=decision,
                    attempts=attempt,
                    retryErrors=retry_errors,
                    durationMs=int((asyncio.get_event_loop().time() - started) * 1000),
                    transcript=transcript,
                )
            except Exception as error:
                last_error = error
                retry_errors.append(str(error)[:300])
                if controller.signal.aborted:
                    raise
        if last_error is not None:
            raise last_error
        raise ValueError("detailed review failed")
    finally:
        timeout_handle.cancel()


def model_decision_to_boundary_review(decision: ModelDecision) -> BoundaryReview:
    return {
        "outcome": decision["outcome"],
        "riskLevel": decision["risk_level"],
        "userAuthorization": decision["user_authorization"],
        "rationale": decision["rationale"],
    }


def current_turn_scope(session_id: str, entries: list[Any]) -> str:
    user_messages = sum(
        1
        for entry in entries
        if isinstance(entry, dict)
        and isinstance(entry.get("message"), dict)
        and entry["message"].get("role") == "user"
    )
    return f"{session_id}:{user_messages}"


def create_reviewer_broker(
    registry: ModelRegistryView,
    config: Config,
    entries_provider: Callable[[], list[Any]],
    session_id_provider: Callable[[], str],
    signal_provider: Callable[[], AbortSignal | None],
    audit: Callable[[Any], None] | None = None,
) -> BoundaryApprovalBroker:
    """Build the fail-closed broker: hard deny -> breaker -> reviewer -> grant."""

    async def reviewer(
        request: BoundaryRequest,
        _context: BoundaryReviewerContext | None,
    ) -> BoundaryReview:
        result = await complete(
            registry,
            config,
            request,
            entries_provider(),
            session_id_provider(),
            signal_provider(),
            _context,
        )
        return model_decision_to_boundary_review(result.decision)

    def hard_deny(request: BoundaryRequest) -> dict[str, str] | None:
        return protected_write_hard_deny(request) or deterministic_hard_deny({
            "surface": "bash_escalated",
            "command": request.get("command"),
            "path": request.get("path"),
            "target": request.get("destination"),
            "toolName": request.get("toolName"),
            "toolInputPreview": request.get("toolInputPreview"),
        })

    return BoundaryApprovalBroker(
        BoundaryApprovalBrokerOptions(
            reviewer=reviewer,
            hardDeny=hard_deny,
            failureMode=config["failureMode"],
            grants=OneShotGrantStore(config["grantTtlMs"]),
            audit=audit,
        )
    )


